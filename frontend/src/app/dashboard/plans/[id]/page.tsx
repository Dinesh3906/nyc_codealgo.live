"use client";

import { useParams, useRouter } from "next/navigation";
import { useState, useEffect } from "react";
import api from "@/lib/api";
import { ArrowLeft, Download, Share2, CheckCircle2, AlertTriangle, Loader2, AlertCircle } from "lucide-react";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";

export default function PlanDetailPage() {
  const { id } = useParams();
  const router = useRouter();
  const [plan, setPlan] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    const fetchPlan = async () => {
      try {
        const res = await api.get(`/plans/${id}`);
        setPlan(res.data);
      } catch (err) {
        console.error("Fetch plan failed:", err);
      } finally {
        setLoading(false);
      }
    };
    fetchPlan();
  }, [id]);

  const handleShare = () => {
    const url = window.location.href;
    navigator.clipboard.writeText(url);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    if (!plan?.analysisResult) return;
    
    import('jspdf').then(async (jsPDFModule) => {
      const jsPDF = jsPDFModule.default;
      const doc = new jsPDF();
      
      // Header
      doc.setFontSize(20);
      doc.setTextColor(15, 23, 42);
      doc.text("NYC Building Code Compliance Report", 20, 25);
      
      doc.setFontSize(10);
      doc.setTextColor(100, 116, 139);
      doc.text(`Project: ${plan.fileName}`, 20, 35);
      doc.text(`Date: ${new Date(plan.createdAt).toLocaleDateString()}`, 20, 40);
      doc.text(`Compliance Score: ${plan.analysisResult.score || 0}%`, 20, 45);
      
      // Summary
      doc.setFontSize(14);
      doc.setTextColor(15, 23, 42);
      doc.text("Executive Summary", 20, 60);
      
      doc.setFontSize(10);
      doc.setTextColor(71, 85, 105);
      const summaryText = plan.analysisResult.summary || "No summary available";
      const splitSummary = doc.splitTextToSize(summaryText, 170);
      doc.text(splitSummary, 20, 70);
      
      // Issues
      const issues = plan.analysisResult.issues || [];
      if (issues.length > 0) {
        let yPos = 70 + (splitSummary.length * 5) + 15;
        
        doc.setFontSize(14);
        doc.setTextColor(15, 23, 42);
        doc.text("Identified Issues", 20, yPos);
        yPos += 10;

        doc.setFontSize(9);
        issues.forEach((issue: any, idx: number) => {
          if (yPos > 270) {
            doc.addPage();
            yPos = 20;
          }
          
          const severityText = (issue.severity || 'minor').toUpperCase();
          doc.setTextColor(220, 38, 38);
          doc.text(`${idx + 1}. [${severityText}]`, 20, yPos);
          
          doc.setTextColor(15, 23, 42);
          doc.setFontSize(10);
          const titleText = issue.title || 'Compliance Issue';
          doc.text(titleText, 20, yPos + 5);
          
          doc.setFontSize(9);
          doc.setTextColor(71, 85, 105);
          const descText = issue.description || 'No description';
          const splitDesc = doc.splitTextToSize(descText, 170);
          doc.text(splitDesc, 20, yPos + 10);
          
          doc.setTextColor(100, 116, 139);
          doc.text(`Code: ${issue.rule || issue.code || 'N/A'}`, 20, yPos + 10 + (splitDesc.length * 4) + 3);
          
          if (issue.suggestion || issue.recommendation) {
            doc.setTextColor(15, 23, 42);
            const recText = issue.suggestion || issue.recommendation;
            const splitRec = doc.splitTextToSize(`Recommendation: ${recText}`, 170);
            doc.text(splitRec, 20, yPos + 10 + (splitDesc.length * 4) + 8);
            yPos += 10 + (splitDesc.length * 4) + 8 + (splitRec.length * 4) + 5;
          } else {
            yPos += 10 + (splitDesc.length * 4) + 8;
          }
        });
      }
      
      // Footer
      const pageCount = (doc as any).internal.getNumberOfPages();
      for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFontSize(8);
        doc.setTextColor(148, 163, 184);
        doc.text(
          `Generated by Brickly AI - Page ${i} of ${pageCount}`,
          doc.internal.pageSize.getWidth() / 2,
          doc.internal.pageSize.getHeight() - 10,
          { align: 'center' }
        );
      }
      
      doc.save(`Compliance_Report_${plan.fileName.split('.')[0]}.pdf`);
    });
  };

  if (loading) {
    return (
      <div className="flex items-center justify-center min-h-[60vh]">
        <div className="text-center space-y-4">
          <Loader2 className="w-8 h-8 animate-spin mx-auto text-primary" />
          <p className="text-sm text-muted-foreground">Loading report...</p>
        </div>
      </div>
    );
  }

  if (!plan) {
    return (
      <div className="flex items-center justify-center min-h-[60vh]">
        <div className="text-center space-y-4">
          <AlertTriangle className="w-12 h-12 mx-auto text-destructive" />
          <div>
            <h2 className="text-xl font-bold">Plan Not Found</h2>
            <p className="text-muted-foreground mt-1">The requested plan could not be found</p>
          </div>
          <Button onClick={() => router.push('/dashboard/plans')}>
            Back to Plans
          </Button>
        </div>
      </div>
    );
  }

  const { analysisResult } = plan;

  return (
    <div className="space-y-6 max-w-6xl">
      <div className="flex items-center justify-between">
        <Button variant="ghost" onClick={() => router.push('/dashboard/plans')}>
          <ArrowLeft className="w-4 h-4 mr-2" />
          Back to Plans
        </Button>
        <div className="flex gap-2">
          <Button variant="outline" onClick={handleShare}>
            {copied ? <CheckCircle2 className="w-4 h-4 mr-2" /> : <Share2 className="w-4 h-4 mr-2" />}
            {copied ? "Copied!" : "Share"}
          </Button>
          <Button onClick={handleDownload}>
            <Download className="w-4 h-4 mr-2" />
            Download Report
          </Button>
        </div>
      </div>

      <Card>
        <CardHeader>
          <div className="flex items-start justify-between">
            <div className="space-y-1">
              <CardTitle className="text-2xl">{plan.fileName}</CardTitle>
              <CardDescription>
                Analyzed on {new Date(plan.createdAt).toLocaleDateString()}
              </CardDescription>
            </div>
            <div className="text-right">
              <div className="text-4xl font-bold text-primary">{analysisResult.score}%</div>
              <p className="text-sm text-muted-foreground">Compliance Score</p>
            </div>
          </div>
        </CardHeader>
      </Card>

      <div className="grid gap-6 md:grid-cols-3">
        <Card className="md:col-span-2">
          <CardHeader>
            <CardTitle>Executive Summary</CardTitle>
          </CardHeader>
          <CardContent>
            <p className="text-muted-foreground leading-relaxed">
              {analysisResult.summary || "No summary available."}
            </p>
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>Issue Breakdown</CardTitle>
          </CardHeader>
          <CardContent className="space-y-4">
            <div className="flex items-center justify-between">
              <span className="text-sm text-muted-foreground">Critical</span>
              <Badge variant="destructive">
                {(analysisResult.issues || []).filter((i: any) => i.severity === 'critical').length}
              </Badge>
            </div>
            <div className="flex items-center justify-between">
              <span className="text-sm text-muted-foreground">Major</span>
              <Badge variant="warning">
                {(analysisResult.issues || []).filter((i: any) => i.severity === 'major').length}
              </Badge>
            </div>
            <div className="flex items-center justify-between">
              <span className="text-sm text-muted-foreground">Minor</span>
              <Badge variant="secondary">
                {(analysisResult.issues || []).filter((i: any) => i.severity === 'minor').length}
              </Badge>
            </div>
          </CardContent>
        </Card>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Identified Issues</CardTitle>
          <CardDescription>
            {analysisResult.issues?.length || 0} issue(s) found during analysis
          </CardDescription>
        </CardHeader>
        <CardContent>
          {!analysisResult.issues || analysisResult.issues.length === 0 ? (
            <div className="text-center py-12 text-muted-foreground">
              <CheckCircle2 className="w-12 h-12 mx-auto mb-4 text-green-500" />
              <p className="font-medium">No Issues Identified</p>
              <p className="text-sm mt-1">This plan appears to meet NYC Building Code requirements</p>
            </div>
          ) : (
            <div className="space-y-4">
              {analysisResult.issues.map((issue: any, i: number) => (
                <Card key={i}>
                  <CardHeader>
                    <div className="flex items-start justify-between">
                      <div className="space-y-1">
                        <CardTitle className="text-lg">{issue.title || "Compliance Issue"}</CardTitle>
                        <CardDescription>Code: {issue.rule || issue.code || 'N/A'}</CardDescription>
                      </div>
                      <Badge variant={
                        issue.severity === 'critical' ? 'destructive' : 
                        issue.severity === 'major' ? 'warning' : 
                        'secondary'
                      }>
                        {issue.severity || 'minor'}
                      </Badge>
                    </div>
                  </CardHeader>
                  <CardContent className="space-y-3">
                    <p className="text-muted-foreground">{issue.description}</p>
                    {(issue.suggestion || issue.recommendation) && (
                      <div className="bg-accent/50 border border-border rounded-md p-3">
                        <p className="text-sm font-medium mb-1">Recommendation</p>
                        <p className="text-sm text-muted-foreground">{issue.suggestion || issue.recommendation}</p>
                      </div>
                    )}
                  </CardContent>
                </Card>
              ))}
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
